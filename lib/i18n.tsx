const dictionaries = { ru, en } as const

export type Dictionary = typeof ru

type I18nContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: Dictionary
}

const I18nContext = createContext<I18nContextValue | null>(null)

function readStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'ru'
  const stored = window.localStorage.getItem(STORAGE_KEY)
  return stored === 'en' || stored === 'ru' ? stored : 'ru'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('ru')

  useEffect(() => {
    setLocaleState(readStoredLocale())
  }, [])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale(next) {
      setLocaleState(next)
      window.localStorage.setItem(STORAGE_KEY, next)
    },
    t: dictionaries[locale],
  }), [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}

export function LanguageSwitcher({ className = '' }: { className?: string }) {
  const { locale, setLocale } = useI18n()
  return (
    <div
      className={`flex text-xs rounded-lg border border-gray-800 overflow-hidden ${className}`}
      role="group"
      aria-label="Language"
    >
      {(['ru', 'en'] as const).map(item => (
        <button
          key={item}
          type="button"
          aria-pressed={locale === item}
          onClick={e => {
            e.preventDefault()
            e.stopPropagation()
            setLocale(item)
          }}
          className={`min-w-[2.5rem] px-3 py-2 uppercase tracking-wide transition ${
            locale === item ? 'bg-indigo-600 text-white' : 'text-gray-500 hover:text-white hover:bg-gray-900'
          }`}
        >
          {item}
        </button>
      ))}
    </div>
  )
}
